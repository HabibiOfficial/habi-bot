/** Cari doa by topik / judul / isi (substring, case-insensitive). */
export function cariDoa(query) {
  const q = String(query || '').toLowerCase().trim()
  if (!q) return DOA
  return DOA.filter(
    (d) =>
      d.topik.includes(q) ||
      d.judul.toLowerCase().includes(q) ||
      d.id.includes(q) ||
      d.arti.toLowerCase().includes(q)
  )
}

export const TOPIK = [...new Set(DOA.map((d) => d.topik))]

export default { DOA, cariDoa, TOPIK }
